"""Turns sounds/*.wav (16 kHz mono 16-bit, as tools/lofi.py writes them) into
src/sounds.h, one int16_t array per file.

Usage: python3 tools/gen_sounds.py
"""
import glob
import os
import wave
import array

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "sounds.h")


def main():
    out = ["// Generated by tools/gen_sounds.py from sounds/*.wav. Do not edit.", "#pragma once",
           "#include <stdint.h>", ""]
    for path in sorted(glob.glob(os.path.join(ROOT, "sounds", "*.wav"))):
        with wave.open(path) as w:
            assert w.getframerate() == 16000 and w.getnchannels() == 1 and w.getsampwidth() == 2, path
            pcm = array.array("h", w.readframes(w.getnframes()))
        name = "SND_" + os.path.splitext(os.path.basename(path))[0].upper()
        out.append(f"static const int16_t {name}[] = {{")
        for i in range(0, len(pcm), 16):
            out.append("    " + ", ".join(str(v) for v in pcm[i:i + 16]) + ",")
        out.append("};")
        out.append(f"static const int {name}_LEN = {len(pcm)};")
        out.append("")
        print(f"{os.path.relpath(path, ROOT)}: {len(pcm) / 16000:.2f} s")
    open(OUT, "w").write("\n".join(out))


main()
