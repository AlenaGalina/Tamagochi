"""Turns words/de-ru.tsv into src/deck.h.

Usage: python3 tools/gen_deck.py

Cards are mixed so each day's ten new words hold some nouns, some verbs and
some of the rest (roughly 4 + 4 + 2), keeping the file's order within each kind.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "words", "de-ru.tsv")
OUT = os.path.join(ROOT, "src", "deck.h")
PATTERN = ["noun", "verb", "noun", "verb", "other"]


def kind(de, forms):
    if de.split()[0] in ("der", "die", "das"):
        return "noun"
    if " hat " in " " + forms or " ist " in " " + forms:
        return "verb"
    return "other"


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    cards = []
    for n, line in enumerate(open(SRC, encoding="utf-8"), 1):
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 3:
            raise SystemExit(f"{SRC}:{n}: expected 3 tab-separated columns")
        cards.append(parts)

    queues = {k: [c for c in cards if kind(c[0], c[1]) == k] for k in ("noun", "verb", "other")}
    mixed = []
    while any(queues.values()):
        for k in PATTERN:
            if queues[k]:
                mixed.append(queues[k].pop(0))

    out = ["// Generated by tools/gen_deck.py from words/de-ru.tsv. Do not edit.", "#pragma once", "",
           "struct Card {", "  const char *de, *forms, *ru;", "};", "",
           "static const Card DECK[] = {"]
    out += [f"    {{{c_string(de)}, {c_string(forms)}, {c_string(ru)}}}," for de, forms, ru in mixed]
    out += ["};", "static const int DECK_SIZE = sizeof(DECK) / sizeof(DECK[0]);", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(out))
    print(f"{len(mixed)} cards -> {os.path.relpath(OUT, ROOT)}")


main()
