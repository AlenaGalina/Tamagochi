"""Turns the ASCII art in art/ into src/sprites.h and an optional preview PNG.

Usage: python3 tools/gen_sprites.py [preview.png]

Pixel codes: . transparent, o outline, f fur, w white, p pink (inner ear),
d dark patch, C cheek, n nose, E left eye, e right eye. Eye and nose positions
are exported so the firmware can draw expressions on top.
Files named legs_*.txt are leg strips that replace the bottom rows of walk.txt.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, "art")
POSES = ["sit", "stand", "lie", "butt", "beg", "walk"]
STRIPS = ["legs_run_a", "legs_run_b"]


def load(name):
    rows = open(os.path.join(ART, name + ".txt")).read().split()
    assert len(set(map(len, rows))) == 1, f"{name}: rows differ in length"
    return rows


def find(rows, ch):
    for y, r in enumerate(rows):
        if ch in r:
            return r.index(ch), y
    return -1, -1


def main():
    art = {p: load(p) for p in POSES + STRIPS}
    out = ["// Generated by tools/gen_sprites.py from art/*.txt. Do not edit.", "#pragma once", "",
           "struct SpriteArt {", "  const char *const *rows;", "  int w, h;",
           "  int eyeX, eyeY, eye2X, eye2Y, noseX, noseY;  // -1 when absent", "};", ""]
    for name, rows in art.items():
        out.append(f"static const char *const ART_{name.upper()}[] = {{")
        out += [f'    "{r}",' for r in rows]
        out.append("};")
    out.append("")
    for name in POSES + STRIPS:
        rows = art[name]
        (ex, ey), (e2x, e2y), (nx, ny) = find(rows, "E"), find(rows, "e"), find(rows, "n")
        out.append(f"static const SpriteArt SPR_{name.upper()} = {{ART_{name.upper()}, {len(rows[0])}, {len(rows)}, "
                   f"{ex}, {ey}, {e2x}, {e2y}, {nx}, {ny}}};")
    open(os.path.join(ROOT, "src", "sprites.h"), "w").write("\n".join(out) + "\n")

    if len(sys.argv) > 1:
        preview(art, sys.argv[1])


def preview(art, path):
    from PIL import Image

    pal = {".": (250, 246, 238), "o": (45, 32, 30), "f": (236, 158, 82), "w": (255, 250, 240),
           "p": (240, 150, 160), "d": (90, 50, 40), "E": (45, 32, 30), "e": (45, 32, 30),
           "C": (245, 160, 170), "n": (45, 32, 30)}
    walk = [list(r) for r in art["walk"]]
    strip = art["legs_run_a"]
    for y, r in enumerate(strip):
        walk[len(walk) - len(strip) + y][: len(r)] = r
    frames = [art[p] for p in POSES] + [["".join(r) for r in walk]]
    S = 8
    W = sum(len(f[0]) + 2 for f in frames)
    H = max(len(f) for f in frames) + 2
    img = Image.new("RGB", (W * S, H * S), pal["."])
    ox = 0
    for rows in frames:
        top = H - 1 - len(rows)
        for y, line in enumerate(rows):
            for x, c in enumerate(line):
                img.paste(pal.get(c, (255, 0, 255)), ((ox + x + 1) * S, (top + y) * S, (ox + x + 2) * S, (top + y + 1) * S))
        ox += len(rows[0]) + 2
    img.save(path)


main()
